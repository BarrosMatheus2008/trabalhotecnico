CREATE DATABASE IF NOT EXISTS controle_estudos;
USE controle_estudos;

CREATE TABLE IF NOT EXISTS usuarios (
    id INT AUTO_INCREMENT PRIMARY KEY,
    nome VARCHAR(100) NOT NULL,
    email VARCHAR(100) UNIQUE NOT NULL,
    senha VARCHAR(255) NOT NULL,
    nivel VARCHAR(20) NOT NULL DEFAULT 'comum',
    criado_em TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS estudos (
    id INT AUTO_INCREMENT PRIMARY KEY,
    usuario_id INT NOT NULL,
    disciplina VARCHAR(120) NOT NULL,
    conteudo TEXT NOT NULL,
    horasEstudadas INT NOT NULL DEFAULT 0,
    status VARCHAR(30) NOT NULL DEFAULT 'Pendente',
    prioridade VARCHAR(20) NOT NULL DEFAULT 'Média',
    criado_em TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    FOREIGN KEY (usuario_id) REFERENCES usuarios(id) ON DELETE CASCADE
);